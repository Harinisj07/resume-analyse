/**
 * Seed initial predefined roles if database is empty or update missing roles.
 * Ensures roles remain fully configurable through the database.
 */
export const seedRoles = async () => {
  try {
    const existingCount = await Role.countDocuments();
    if (existingCount === 0) {
      console.log('[Seed] Seeding 12 predefined target roles into MongoDB...');
      await Role.insertMany(predefinedRoles);
      console.log('[Seed] Predefined roles successfully seeded.');
      return;
    }

    // Upsert any missing roles while preserving customized database roles
    for (const roleData of predefinedRoles) {
      const exists = await Role.findOne({ name: roleData.name });
      if (!exists) {
        await Role.create(roleData);
        console.log(`[Seed] Added missing target role: ${roleData.name}`);
      }
    }
  } catch (error) {
    console.error('[Seed] Error seeding roles:', error.message);
  }
};

export default seedRoles;
